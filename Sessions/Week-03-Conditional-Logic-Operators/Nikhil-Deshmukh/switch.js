let day = "Monday";

switch (day){
    case "Tuesday":
    console.log("Start of the day");
    break;
    case "Friday":
    console.log("Almost a weekend");
    break;
    default:
    console.log("Normal day");
}

let time= "11:00AM";

switch (time){
    case "11:00AM":
    console.log("Login time");
    break;
    case "8:00AM":
    console.log("Log out time");
    break;
    default:
    console.log("Late");
}